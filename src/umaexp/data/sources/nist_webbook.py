"""NIST Chemistry WebBook (SRD 69): vibrational fundamentals (Shimanouchi 1972).

Deterministic extraction of the "Vibrational and/or electronic energy
levels" table (cbook.cgi?ID=<id>&Mask=800). Page layout verified 2026-09-26.

Curation decisions (recorded in each record's transformation_history):
  * value_kind = EVALUATED: "Selected Freq." values of a critical compilation,
    not raw spectra; the IR/Raman columns are kept as labels;
  * the rating letter's range comes from the page's own Notes table
    (e.g. "A: 0~1 cm-1 uncertainty"); standard sd = upper bound / 2;
  * duplicated rows for inversion-doubled levels (e.g. NH3) are merged
    into one fundamental and flagged `inversion_doubling`;
  * footnotes are mapped to quality flags (silent mode, Coriolis-observed,
    Fermi resonance, calculated/estimated, overlapped, condensed phase).
    Note codes are read from the IR, Raman AND Comments columns (v2: FR/OC/OV
    live in the Comments column and were missed by v1);
  * silent_mode = inactive ("ia") in BOTH the IR and Raman columns (v1 flagged
    every mode inactive in either column, i.e. every mode of a centrosymmetric
    molecule, which carried no information);
  * species: the WebBook renders double primes as nothing ("a" for a'' in Cs
    tables); on a page whose species use primes, an unprimed species is
    restored to double-primed (v2);
  * phase = gas only if the IR or Raman phase column says gas; empty phase
    columns are flagged `phase_not_stated` (not assumed gas), non-gas phases
    `condensed_phase_only`;
  * temperature is not given for band origins and is left missing.
Copyright: the compilation is (c) U.S. Secretary of Commerce under the
Standard Reference Data Act; raw pages and extracted values stay local
(data/raw, data/processed are git-ignored) and are regenerated by script.
"""

from __future__ import annotations

