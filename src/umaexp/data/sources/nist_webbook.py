CBOOK = "https://webbook.nist.gov/cgi/cbook.cgi"
PARSER_VERSION = "nist_shimanouchi_v3.1"
LICENSE = "NIST Standard Reference Data (SRD 69); Standard Reference Data Act"
LICENSE_URL = "https://www.nist.gov/srd/public-law"
CITATION = ("T. Shimanouchi, Tables of Molecular Vibrational Frequencies Consolidated Volume I, "
            "NSRDS-NBS 39, National Bureau of Standards (1972); via NIST Chemistry WebBook, SRD 69.")


def fetch(nist_id: str, raw_dir: str, mask: int = 800, sleep_s: float = 1.0, timeout: float = 30.0) -> dict:
    """Download one WebBook page; returns {path, sha256, url, retrieval_date}."""
    import requests

    url = f"{CBOOK}?ID={nist_id}&Mask={mask}"
    os.makedirs(raw_dir, exist_ok=True)
    r = requests.get(url, timeout=timeout, headers={"User-Agent": "umaexp research data curation"})
    r.raise_for_status()
    today = dt.date.today().isoformat()
    path = os.path.join(raw_dir, f"{nist_id}_mask{mask}_{today}.html")
    with open(path, "wb") as f:
        f.write(r.content)
    time.sleep(sleep_s)
    return {"path": path, "sha256": hashlib.sha256(r.content).hexdigest(), "url": url, "retrieval_date": today}


class _TableParser(HTMLParser):
    """Collects rows of the vibrational table and the notes table."""

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.tables: list[dict] = []
        self._table = None
        self._row = None
        self._cell = None
        self._in_h3 = False
        self.h3: list[str] = []

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if tag == "table":
            self._table = {"summary": a.get("summary"), "aria": a.get("aria-label"), "rows": []}
        elif tag == "tr" and self._table is not None:
            self._row = []
        elif tag in ("td", "th") and self._row is not None:
            self._cell = {"text": "", "links": [], "id": None}
        elif tag == "a" and self._cell is not None:
            if a.get("id"):
                self._cell["id"] = a["id"]
            self._cell["_link"] = ""
        elif tag == "h3":
            self._in_h3 = True
            self.h3.append("")

    def handle_endtag(self, tag):
        if tag == "table" and self._table is not None:
            self.tables.append(self._table)
            self._table = None
        elif tag == "tr" and self._row is not None and self._table is not None:
            self._table["rows"].append(self._row)
            self._row = None
        elif tag in ("td", "th") and self._cell is not None and self._row is not None:
            self._cell["text"] = " ".join(self._cell["text"].split())
            self._cell.pop("_link", None)
            self._row.append(self._cell)
            self._cell = None
        elif tag == "a" and self._cell is not None and "_link" in self._cell:
            t = self._cell.pop("_link").strip()
            if t:
                self._cell["links"].append(t)
        elif tag == "h3":
            self._in_h3 = False

    def handle_data(self, data):
        if self._cell is not None:
            self._cell["text"] += data
            if "_link" in self._cell:
                self._cell["_link"] += data
        if self._in_h3 and self.h3:
            self.h3[-1] += data


def _num(text: str) -> float | None:
    m = re.search(r"[-+]?\d+(?:\.\d+)?", text.replace("\xa0", " "))
    return float(m.group()) if m else None


EXPECTED_HEADER = ["Sym.", "No", "Approximate", "Selected Freq.", "Infrared", "Raman", "Comments"]
# every note code seen on the curated pages (rating, intensity, polarization, inactive, FR/OC/OV);
# anything else fails closed as `unknown_note_code` (v3)
ALLOWED_CODES = {"A", "B", "C", "D", "E", "FR", "OC", "OV", "M", "S", "VS", "VW", "W", "b", "vb", "p", "dp", "ia"}
_COMMENT_OK = [re.compile(r"^(FR|OC|OV)(\s*\(.*\))?$"),
               re.compile(r"^Observed through Coriolis interaction with ν\s*\d+$"),
               re.compile(r"^(anti)?symmetric level$")]
_PLAIN = re.compile(r"^\d+(\.\d+)?$")


def _cell_value(cell: dict) -> tuple[float | None, bool]:
    """Numeric content of a value cell with its note-code link texts removed; (value, is_plain)."""
    text = cell["text"]
    for code in cell["links"]:
        text = text.replace(code, " ")
    text = text.replace("\xa0", " ").strip()
    if not text:
        return None, True
    return (float(text), True) if _PLAIN.match(text) else (_num(text), False)


def parse_vibrational_page(page: str) -> dict:
    """Return {'symmetry', 'symmetry_number', 'rows', 'notes', 'has_table', 'page_errors'} (v3: fails closed).

    page_errors (any -> the page is not usable): heading/table count mismatch,
    several tables without a single gas-phase one, unexpected column layout,
    table not attributed to Shimanouchi (1972).
    """
    p = _TableParser()
    p.feed(page)
    vibs = [t for t in p.tables if t["summary"] == "Vibrational data"]
    notes_t = next((t for t in p.tables if (t["aria"] or "").lower() == "list of notes"), None)
    notes = {}
    if notes_t:
        for row in notes_t["rows"]:
            if len(row) >= 2:
                code = row[0]["text"] or row[0]["id"]  # link text ("A") is what rows reference
                notes[code.strip()] = row[1]["text"]
    errors: list[str] = []
    heads = [html.unescape(h).replace("\xa0", " ") for h in p.h3 if "Symmetry:" in html.unescape(h)]
    if not vibs:
        return {"symmetry": None, "symmetry_number": None, "rows": [], "notes": notes, "has_table": False,
                "page_errors": []}
    if len(heads) != len(vibs):
        errors.append(f"{len(vibs)} vibrational tables but {len(heads)} symmetry headings")
    k = 0
    if len(vibs) > 1:
        gas = [i for i, h in enumerate(heads) if h.strip().lower().startswith("gas")]
        if len(gas) == 1:
            k = gas[0]
        else:
            errors.append("several vibrational tables without a single gas-phase table")
    vib = vibs[k]
    header = next(([" ".join(c["text"].replace("\xa0", " ").split()) for c in r] for r in vib["rows"]
                   if r and r[0]["text"].replace("\xa0", " ").strip() in ("Sym.", "Species")), None)
    if header != EXPECTED_HEADER:
        errors.append(f"unexpected table header {header}")
    segs = re.split(r'<table[^>]*summary="Vibrational data"', page)
    after = re.sub(r"<[^>]+>", " ", segs[k + 1]) if len(segs) > k + 1 else ""
    after = after.split("Symmetry:")[0]
    if not re.search(r"Source:\s*Shimanouchi,\s*1972", html.unescape(after)):
        errors.append("table not attributed to Shimanouchi (1972)")
    sym = sigma = None
    if k < len(heads):
        m = re.search(r"Symmetry:\s*(.+?)\s+Symmetry Number\s*\S*\s*=\s*(\d+)", heads[k])
        if m:
            sym = re.sub(r"\s+", "", m.group(1)).replace("ν", "v")
            sigma = int(m.group(2))
    if sym is None:
        errors.append("no point group for the selected table")
    rows = []
    for r in vib["rows"]:
        if len(r) < 10 or r[0]["text"] in ("", "Sym.", "Species") or not r[1]["text"].strip().isdigit():
            continue
        species = r[0]["text"].replace(" ", "").replace("\u2033", "''").replace("\u2032", "'")
        sel, sel_plain = _cell_value({"text": r[3]["text"], "links": []})
        ir, ir_plain = _cell_value(r[5])
        ra, ra_plain = _cell_value(r[7])
        rows.append({
            "species": species,
            "number": int(r[1]["text"]),
            "type": r[2]["text"],
            "selected": sel,
            "rating": (r[4]["links"] or [r[4]["text"].strip()])[0] if (r[4]["links"] or r[4]["text"].strip()) else None,
            "ir": ir,
            "ir_codes": r[5]["links"],
            "ir_phase": r[6]["text"] or None,
            "raman": ra,
            "raman_codes": r[7]["links"],
            "raman_phase": r[8]["text"] or None,
            "comments": r[9]["text"] or None,
            "comment_codes": r[9]["links"],
            "numeric_ok": bool(sel_plain and sel is not None and ir_plain and ra_plain),
        })
    if any("'" in r["species"] for r in rows):  # primed species: restore dropped double primes
        for r in rows:
            if "'" not in r["species"]:
                r["species_raw"] = r["species"]
                r["species"] = r["species"] + "''"
    return {"symmetry": sym, "symmetry_number": sigma, "rows": rows, "notes": notes, "has_table": True,
            "page_errors": errors}


def species_degeneracy(species: str) -> int:
    s = species.lower()
    if s.startswith(("e", "pi", "π")):
        return 2
    if s.startswith(("f", "t")):
        return 3
    return 1


def _rating_range(note: str | None) -> tuple[float, float] | None:
    if not note:
        return None
    m = re.search(r"(\d+(?:\.\d+)?)\s*~\s*(\d+(?:\.\d+)?)\s*cm", note)
    return (float(m.group(1)), float(m.group(2))) if m else None


def _flags(row: dict, notes: dict, merged: bool) -> list[str]:
    flags = []
    codes = set(row["ir_codes"]) | set(row["raman_codes"]) | set(row.get("comment_codes", []))
    if row["rating"]:
        codes.add(row["rating"])
    texts = " ".join([notes.get(c, "") for c in codes] + [row["comments"] or ""]).lower()
    if codes - ALLOWED_CODES:
        flags.append("unknown_note_code")
    comment = " ".join((row["comments"] or "").split())
    if comment and not any(rx.match(comment) for rx in _COMMENT_OK):
        flags.append("free_text_comment")
    if not row.get("numeric_ok", True):
        flags.append("nonnumeric_value")
    if "ia" in row["ir_codes"] and "ia" in row["raman_codes"]:
        flags.append("silent_mode")
    if "OV" in codes or "overlapped" in texts:
        flags.append("overlapped_band")
    if "coriolis" in texts:
        flags.append("observed_via_coriolis_interaction")
    if "FR" in codes or "fermi" in texts:
        flags.append("fermi_resonance")
    if "OC" in codes or any(k in texts for k in ("calc", "estimated", "est.")):
        flags.append("not_directly_observed")
    if re.search(r"(anti)?symmetric level", texts):  # tunnelling-split level, merged or not (critic #3 S2-2)
        flags.append("inversion_doubling")
    phases = {(row["ir_phase"] or "").lower(), (row["raman_phase"] or "").lower()} - {""}
    if not phases:
        flags.append("phase_not_stated")
    elif "gas" not in phases:
        flags.append("condensed_phase_only")
    return flags


def _gas_column_values(rows: list[dict]) -> list[float]:
    out = []
    for r in rows:
        if (r["ir_phase"] or "").lower() == "gas" and r["ir"] is not None:
            out.append(r["ir"])
        if (r["raman_phase"] or "").lower() == "gas" and r["raman"] is not None:
            out.append(r["raman"])
    return out


def to_observations(parsed: dict, identity: MolecularIdentity, fetch_info: dict,
                    molecule_group: str, scaffold_group: str | None = None) -> list[Observation]:
    """One EVALUATED observation per fundamental (merging doubled levels)."""
    by_mode: dict[tuple[str, int], list[dict]] = {}
    for r in parsed["rows"]:
        by_mode.setdefault((r["species"], r["number"]), []).append(r)
    out = []
    for (species, number), rows in sorted(by_mode.items(), key=lambda kv: kv[0][1]):
        r0 = rows[0]
        merged = len(rows) > 1
        note = parsed["notes"].get(r0["rating"] or "", None)
        rng = _rating_range(note)
        flags = _flags(r0, parsed["notes"], merged)
        if rng is not None and rng[1] > 15.0:
            flags.append("rating_uncertainty_gt_15cm")
        doubled = merged and all((r["comments"] or "").strip().endswith("level") for r in rows)
        if merged and not doubled and len({(r["selected"], r["rating"]) for r in rows}) > 1:
            flags.append("conflicting_duplicate_rows")
        gas_vals = _gas_column_values(rows)
        if r0["selected"] is None:
            flags.append("nonnumeric_value")
        if r0["selected"] is None or not gas_vals or min(abs(v - r0["selected"]) for v in gas_vals) > 1.0:
            flags.append("selected_not_gas_column")
        if merged:
            for r in rows[1:]:
                for f in _flags(r, parsed["notes"], merged):
                    if f not in flags:
                        flags.append(f)
        phase = Phase.UNKNOWN if ("phase_not_stated" in flags or "condensed_phase_only" in flags) else Phase.GAS
        steps = [
            TransformStep(step="fetch", tool="requests", version="-",
                          parameters={"url": fetch_info["url"], "sha256": fetch_info["sha256"]}),
            TransformStep(step="parse_shimanouchi_table", tool="umaexp", version=PARSER_VERSION,
                          parameters={"merged_rows": len(rows)}),
            TransformStep(step="uncertainty_from_rating", tool="umaexp", version=PARSER_VERSION,
                          parameters={"rating": r0["rating"], "note": note, "rule": "sd = upper/2"}),
        ]
        out.append(Observation(
            observation_id=f"nist_vib:{identity.system_id}:{species}{number}",
            system_ids=[identity.system_id],
            family="vibrational",
            quantity="vibrational_fundamental_wavenumber",
            definition="Selected fundamental vibrational wavenumber (band origin) from the Shimanouchi "
                       "1972 compilation; includes anharmonicity (not a harmonic frequency).",
            value=float(r0["selected"]) if r0["selected"] is not None else float("nan"),
            units="cm^-1",
            labels={"species": species, "mode_number": number, "approximate_type": r0["type"],
                    "degeneracy": species_degeneracy(species), "point_group": parsed["symmetry"],
                    "symmetry_number": parsed["symmetry_number"],
                    "ir": [r["ir"] for r in rows], "ir_phase": [r["ir_phase"] for r in rows],
                    "raman": [r["raman"] for r in rows], "raman_phase": [r["raman_phase"] for r in rows],
                    "comments": [r["comments"] for r in rows], "rating": r0["rating"]},
            uncertainty=Uncertainty(kind=UncertaintyType.RANGE_RATING if rng else UncertaintyType.UNKNOWN,
                                    range=rng, source_text=note, conversion_rule="sd = upper/2" if rng else None),
            value_kind=ValueKind.EVALUATED,
            conditions=Conditions(phase=phase, protocol="IR/Raman band origins (compiled)",
                                  missing=["temperature", "pressure"]),
            compatible_uma_tasks=["omol"],
            forward_model={"name": "harmonic_to_fundamental", "note": "requires anharmonic/NQE model"},
            provenance=Provenance(
                source_name="NIST Chemistry WebBook (SRD 69) - Shimanouchi 1972",
                source_url=fetch_info["url"],
                source_record_id=f"{identity.cas or identity.system_id}:{species}{number}",
                retrieval_date=dt.date.fromisoformat(fetch_info["retrieval_date"]),
                dataset_version="SRD 69 (web, retrieved)",
                license=LICENSE, license_url=LICENSE_URL,
                redistribution=Redistribution.RESTRICTED,
                citation=CITATION,
                transformation_history=steps,
            ),
            groups=SplitGroups(molecule_group=molecule_group, scaffold_group=scaffold_group,
                               provenance_group="nist_shimanouchi_1972", publication_group=None),
            quality_flags=flags + ["primary_reference_not_resolved"],
        ))
    return out
